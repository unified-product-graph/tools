// ─── Edge → relation property ─────────────────────────────────────────────────

/**
 * Given a UPG edge type and the target database name, returns the Notion
 * relation property spec to add to the source database.
 */
export function generateRelationProperty(
  edgeType: string,
  targetDatabaseName: string,
): NotionRelationProperty {
  const verbs = EDGE_RELATION_VERBS[edgeType]
  const forwardVerb = verbs?.forward ?? toTitleCase(edgeType.replace(/_/g, ' '))
  const reverseVerb = verbs?.reverse ?? `← ${targetDatabaseName}`

  return {
    name: forwardVerb,
    target_database_name: targetDatabaseName,
    two_way: true,
    reverse_name: reverseVerb,
    upg_edge_type: edgeType,
  }
}

// ─── Node → page properties ───────────────────────────────────────────────────

/**
 * Maps a UPG node's fields to Notion page property values.
 */
function mapNodeToPageProperties(node: UPGBaseNode): NotionPageProperties {
  const props: NotionPageProperties = {
    Name: { type: 'title', value: node.title },
    'UPG ID': { type: 'unique_id', value: node.id },
  }

  if (node.description) {
    props['Description'] = { type: 'rich_text', value: node.description }
  }

  if (node.status) {
    props['Status'] = { type: 'status', value: node.status }
  }

  return props
}

// ─── Workspace plan generator ─────────────────────────────────────────────────

/**
 * Given a complete UPG graph (nodes + edges), returns the full set of Notion
 * API calls needed to create the workspace.
 *
 * Execution order for the caller:
 *   1. Create all databases (from `databases`)
 *   2. Create all pages once database IDs are known (from `pages`)
 *   3. Populate relation properties once page IDs are known (from `relations`)
 */
export function generateNotionWorkspace(
  nodes: UPGBaseNode[],
  edges: UPGEdge[],
): NotionWorkspacePlan {
  const warnings: string[] = []
  const databasePlans = new Map<string, NotionDatabasePlan>()

  // ── 1. Collect entity types from nodes ───────────────────────────────────
  const entityTypes = new Set<string>()
  for (const node of nodes) {
    entityTypes.add(node.type as string)
  }

  // ── 2. Create one database plan per entity type ──────────────────────────
  for (const entityType of entityTypes) {
    const databaseName = getDatabaseName(entityType)
    databasePlans.set(entityType, {
      entity_type: entityType,
      database_name: databaseName,
      properties: generateDatabaseSchema(entityType),
      relations: [],
    })
  }

  // ── 3. Process edges → add relation properties to source databases ────────
  const processedEdgeTypes = new Set<string>()

  for (const edge of edges) {
    const sourceNode = nodes.find((n) => n.id === edge.source)
    const targetNode = nodes.find((n) => n.id === edge.target)

    if (!sourceNode || !targetNode) {
      warnings.push(
        `Edge "${edge.type}" references unknown node. Skipped. ` +
          `(source: ${edge.source}, target: ${edge.target})`,
      )
      continue
    }

    const sourceType = sourceNode.type as string
    const targetType = targetNode.type as string
    const edgeKey = `${edge.type}::${sourceType}::${targetType}`

    // Deduplicate: only add the relation property once per edge type + type pair
    if (processedEdgeTypes.has(edgeKey)) continue
    processedEdgeTypes.add(edgeKey)

    const sourcePlan = databasePlans.get(sourceType)
    if (!sourcePlan) continue

    const targetDatabaseName = getDatabaseName(targetType)
    const relationProp = generateRelationProperty(edge.type, targetDatabaseName)

    // Avoid duplicate relation properties on the same database
    const alreadyAdded = sourcePlan.relations.some(
      (r) => r.upg_edge_type === edge.type && r.target_database_name === targetDatabaseName,
    )
    if (!alreadyAdded) {
      sourcePlan.relations.push(relationProp)
    }
  }

  // ── 4. Build page plans (one per UPG node) ────────────────────────────────
  const pages: NotionPagePlan[] = nodes.map((node) => ({
    entity_type: node.type as string,
    database_name: getDatabaseName(node.type as string),
    properties: mapNodeToPageProperties(node),
    source_node_id: node.id,
  }))

  // ── 5. Build relation links (populated after pages are created) ───────────
  // Source/target page IDs are not yet known: they will be filled in by the
  // caller once Notion page creation responses are received. We emit the
  // structural plan so the caller knows which pages to link.
  const relations: NotionRelationLink[] = edges
    .filter((edge) => {
      const src = nodes.find((n) => n.id === edge.source)
      const tgt = nodes.find((n) => n.id === edge.target)
      if (!src || !tgt) return false
      if (!EDGE_RELATION_VERBS[edge.type]) {
        warnings.push(
          `Edge type "${edge.type}" has no Notion relation verb mapping. ` +
            `The edge will not appear as a Notion relation property. ` +
            `Add it to EDGE_RELATION_VERBS to enable this.`,
        )
        return false
      }
      return true
    })
    .map((edge) => {
      const verbs = EDGE_RELATION_VERBS[edge.type]
      return {
        source_page_id: edge.source, // placeholder: caller replaces with Notion page ID
        relation_property: verbs.forward,
        target_page_id: edge.target, // placeholder: caller replaces with Notion page ID
        edge_type: edge.type,
      }
    })

  // ── 6. Warn on entity types with no database schema ──────────────────────
  for (const entityType of entityTypes) {
    if (!ENTITY_DATABASE_NAMES[entityType]) {
      warnings.push(
        `Entity type "${entityType}" has no canonical Notion database name. ` +
          `A database name was auto-generated. Add it to ENTITY_DATABASE_NAMES for a stable name.`,
      )
    }
  }

  return {
    databases: Array.from(databasePlans.values()),
    pages,
    relations,
    warnings,
  }
}

// ─── Utilities ────────────────────────────────────────────────────────────────

function toTitleCase(str: string): string {
  return str.replace(/\b\w/g, (c) => c.toUpperCase())
}
