/**
 * Notion Schema Generator: UPG → Notion (write direction)
 *
 * Given a UPG graph (nodes + edges), emits the full set of Notion API
 * payloads needed to create a correctly structured, edge-linked workspace:
 *
 *   1. One Notion database per UPG entity type present in the graph
 *   2. Relation properties wired between databases to represent UPG edges
 *   3. One Notion page per UPG node, with properties mapped from the node
 *   4. Relation links populated once page IDs are known
 *
 * This is the primary integration direction for the Notion adapter.
 * No HTTP calls are made here: this module produces a NotionWorkspacePlan
 * that the caller executes against the Notion API.
 *
 * Algorithm (from notion-mapping.md §6):
 *   1. Read the UPG graph (entity types + edge types present)
 *   2. For each entity type → create a Notion database with canonical properties
 *   3. For each edge type → create a relation property on the source database
 *   4. For each node → create a Notion page in the corresponding database
 *   5. Return the full workspace plan
 */

